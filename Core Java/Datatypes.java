class Datatypes{
    public static void main(String[] args){
        int i = 10;
        float f = 10;
        double d = 10.1234567809;
        boolean b = true;
        char ch = 'a';
        System.out.println(i);
        System.out.println(f);
        System.out.println(d);
        System.out.println(b);
        System.out.println(ch);
    }
}